CREATE TABLE PERSONA (
  IDPER      INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
  DNIPER     CHAR(8),
  NOMPER     VARCHAR2(60),
  APEPER     VARCHAR2(80),
  EMAPER     VARCHAR2(80),
  CELPER     CHAR(9),
  TIPPER     CHAR(1),
  FECNACPER  DATE,
  ESTPER     CHAR(1),
  CONSTRAINT PER_PK PRIMARY KEY (IDPER)
);

CREATE TABLE CATEGORIA (
  IDCAT   INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
  NOMCAT  VARCHAR2(60),
  CONSTRAINT CAT_PK PRIMARY KEY (IDCAT)
);

CREATE TABLE PRODUCTO (
  CODPROD  CHAR(3),
  NOMPRO   VARCHAR2(50),
  IDCAT    NUMBER,      -- FK a agregar luego
  PREPRO   NUMBER(8,2),
  STOCKPRO NUMBER,
  ESTPRO   CHAR(1),
  CONSTRAINT PRO_PK PRIMARY KEY (CODPROD)
);

CREATE TABLE VENTA (
  IDVEN     INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
  FECVEN    DATE,
  IDCLI     NUMBER,  -- FK a agregar luego (cliente -> PERSONA)
  IDVEND    NUMBER,  -- FK a agregar luego (vendedor -> PERSONA)
  TIPPAGVEN CHAR(1),
  ESTVEN    CHAR(1),
  CONSTRAINT VEN_PK PRIMARY KEY (IDVEN)
);

CREATE TABLE VENTA_DETALLE (
  IDVENDET INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
  IDVEN    NUMBER,     -- FK a agregar luego -> VENTA
  CODPROD  CHAR(3),    -- FK a agregar luego -> PRODUCTO
  CANVENDET NUMBER,
  CONSTRAINT VENDET_PK PRIMARY KEY (IDVENDET)
);

COMMIT;

-- 3) Agregar constraints (FK) por separado con ALTER TABLE
ALTER TABLE PRODUCTO
  ADD CONSTRAINT FK_PRODUCTO_CATEGORIA
  FOREIGN KEY (IDCAT)
  REFERENCES CATEGORIA (IDCAT);

ALTER TABLE VENTA
  ADD CONSTRAINT FK_VENTA_CLIENTE
  FOREIGN KEY (IDCLI)
  REFERENCES PERSONA (IDPER);

ALTER TABLE VENTA
  ADD CONSTRAINT FK_VENTA_VENDEDOR
  FOREIGN KEY (IDVEND)
  REFERENCES PERSONA (IDPER);

ALTER TABLE VENTA_DETALLE
  ADD CONSTRAINT FK_VDET_VENTA
  FOREIGN KEY (IDVEN)
  REFERENCES VENTA (IDVEN);

ALTER TABLE VENTA_DETALLE
  ADD CONSTRAINT FK_VDET_PRODUCTO
  FOREIGN KEY (CODPROD)
  REFERENCES PRODUCTO (CODPROD);

COMMIT;

